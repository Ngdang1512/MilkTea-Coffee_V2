-- Thông báo cho khách hàng và nội dung trả lời phản hồi từ nhân viên.
-- Có thể chạy lại an toàn trên database đã tạo từ CRM_Create_All.sql.
BEGIN;

ALTER TABLE phan_hoi
  ADD COLUMN IF NOT EXISTS phan_hoi_cua_nhan_vien text;
ALTER TABLE phan_hoi
  ADD COLUMN IF NOT EXISTS ngay_phan_hoi timestamptz;

CREATE TABLE IF NOT EXISTS thong_bao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tai_khoan_id bigint NOT NULL REFERENCES tai_khoan(id) ON DELETE CASCADE,
  loai varchar(30) NOT NULL,
  tieu_de varchar(255) NOT NULL,
  noi_dung text NOT NULL,
  lien_ket varchar(100),
  da_doc boolean NOT NULL DEFAULT false,
  ngay_tao timestamptz NOT NULL DEFAULT now(),
  ngay_doc timestamptz,
  CONSTRAINT ck_thong_bao_loai CHECK (loai IN ('survey', 'feedback_reply')),
  CONSTRAINT ck_thong_bao_tieu_de CHECK (length(trim(tieu_de)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_thong_bao_khach_hang_ngay_tao
  ON thong_bao(tai_khoan_id, ngay_tao DESC);

COMMIT;