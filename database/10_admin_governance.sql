-- Governance features for the Admin and Manager portals.
-- Safe to run more than once after the CRM schema and migration 07.
BEGIN;

CREATE TABLE IF NOT EXISTS nhan_vien_noi_bo (
  tai_khoan_id bigint PRIMARY KEY REFERENCES tai_khoan(id) ON DELETE CASCADE,
  ho_ten varchar(150) NOT NULL,
  chuc_vu varchar(150) NOT NULL,
  bo_phan varchar(150) NOT NULL DEFAULT '',
  ngay_cap_nhat timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_nhan_vien_ho_ten CHECK (length(trim(ho_ten)) > 0),
  CONSTRAINT ck_nhan_vien_chuc_vu CHECK (length(trim(chuc_vu)) > 0)
);

INSERT INTO nhan_vien_noi_bo(tai_khoan_id, ho_ten, chuc_vu)
SELECT id, ten_dang_nhap, 'Chưa cập nhật'
  FROM tai_khoan
 WHERE vai_tro = 'manager'
ON CONFLICT (tai_khoan_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS yeu_cau_admin_khach_hang (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nguoi_yeu_cau_id bigint NOT NULL REFERENCES tai_khoan(id) ON DELETE RESTRICT,
  khach_hang_id bigint REFERENCES tai_khoan(id) ON DELETE SET NULL,
  khach_hang_ten varchar(150),
  loai varchar(30) NOT NULL DEFAULT 'lock_customer',
  ly_do text NOT NULL,
  trang_thai varchar(20) NOT NULL DEFAULT 'pending',
  nguoi_quyet_dinh_id bigint REFERENCES tai_khoan(id) ON DELETE SET NULL,
  ghi_chu_quyet_dinh text,
  ngay_tao timestamptz NOT NULL DEFAULT now(),
  ngay_quyet_dinh timestamptz,
  CONSTRAINT ck_yeu_cau_loai CHECK (loai IN ('lock_customer', 'unlock_customer', 'delete_customer')),
  CONSTRAINT ck_yeu_cau_trang_thai CHECK (trang_thai IN ('pending', 'approved', 'rejected')),
  CONSTRAINT ck_yeu_cau_ly_do CHECK (length(trim(ly_do)) > 0)
);

ALTER TABLE yeu_cau_admin_khach_hang
  ADD COLUMN IF NOT EXISTS khach_hang_ten varchar(150);

UPDATE yeu_cau_admin_khach_hang r
   SET khach_hang_ten = h.ho_ten
  FROM khach_hang h
 WHERE r.khach_hang_id = h.tai_khoan_id
   AND r.khach_hang_ten IS NULL;

ALTER TABLE yeu_cau_admin_khach_hang
  DROP CONSTRAINT IF EXISTS ck_yeu_cau_loai;

ALTER TABLE yeu_cau_admin_khach_hang
  ADD CONSTRAINT ck_yeu_cau_loai CHECK (loai IN ('lock_customer', 'unlock_customer', 'delete_customer'));

CREATE INDEX IF NOT EXISTS ix_yeu_cau_admin_trang_thai_ngay
  ON yeu_cau_admin_khach_hang(trang_thai, ngay_tao DESC);

COMMIT;
