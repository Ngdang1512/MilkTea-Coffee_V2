-- Manager unlock requests are separate from customer governance requests.
-- Safe to run more than once after CRM_Create_All.sql and migration 10.
BEGIN;

CREATE TABLE IF NOT EXISTS yeu_cau_mo_khoa_manager (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manager_id bigint NOT NULL REFERENCES tai_khoan(id) ON DELETE CASCADE,
  reason text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'pending',
  decided_by bigint REFERENCES tai_khoan(id) ON DELETE SET NULL,
  decision_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  decided_at timestamptz,
  CONSTRAINT ck_manager_unlock_status CHECK (status IN ('pending', 'approved', 'rejected')),
  CONSTRAINT ck_manager_unlock_reason CHECK (length(trim(reason)) BETWEEN 5 AND 2000)
);

CREATE INDEX IF NOT EXISTS ix_manager_unlock_status_created
  ON yeu_cau_mo_khoa_manager(status, created_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS ux_manager_unlock_pending
  ON yeu_cau_mo_khoa_manager(manager_id) WHERE status = 'pending';

COMMIT;
