BEGIN;
SET TIME ZONE 'Asia/Ho_Chi_Minh';
CREATE TYPE "vai_tro" AS ENUM (
  'admin',
  'manager',
  'staff',
  'customer'
);

CREATE TYPE "trang_thai_tai_khoan" AS ENUM (
  'active',
  'locked'
);

CREATE TYPE "gioi_tinh" AS ENUM (
  'nam',
  'nu',
  'khac',
  'khong_cung_cap'
);

CREATE TYPE "trang_thai_phan_hoi" AS ENUM (
  'moi',
  'da_xem',
  'da_tiep_thu'
);

CREATE TYPE "trang_thai_khao_sat" AS ENUM (
  'nhap',
  'dang_mo',
  'da_dong'
);

CREATE TABLE "tai_khoan" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ten_dang_nhap" varchar(100) UNIQUE NOT NULL,
  "mat_khau_hash" varchar(255) NOT NULL,
  "vai_tro" vai_tro NOT NULL DEFAULT 'customer',
  "trang_thai" trang_thai_tai_khoan NOT NULL DEFAULT 'active',
  "nguoi_tao_id" bigint,
  "ngay_tao" timestamptz NOT NULL DEFAULT (now()),
  "ngay_cap_nhat" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_tai_khoan_username" CHECK (length(trim(ten_dang_nhap)) >= 3),
  CONSTRAINT "ck_tai_khoan_hash" CHECK (length(mat_khau_hash) >= 20)
);

CREATE TABLE "nhom_so_thich" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ten_nhom" varchar(100) UNIQUE NOT NULL,
  "mo_ta" text,
  "dang_su_dung" boolean NOT NULL DEFAULT true,
  CONSTRAINT "ck_so_thich_ten" CHECK (length(trim(ten_nhom)) > 0)
);

CREATE TABLE "khach_hang" (
  "tai_khoan_id" bigint PRIMARY KEY NOT NULL,
  "ma_thanh_vien" varchar(30) UNIQUE NOT NULL,
  "ho_ten" varchar(150) NOT NULL,
  "nam_sinh" smallint NOT NULL,
  "gioi_tinh" gioi_tinh NOT NULL DEFAULT 'khong_cung_cap',
  "so_thich_id" bigint NOT NULL,
  "ngay_cap_nhat" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_khach_hang_ho_ten" CHECK (length(trim(ho_ten)) > 0),
  CONSTRAINT "ck_khach_hang_ma" CHECK (length(trim(ma_thanh_vien)) > 0),
  CONSTRAINT "ck_khach_hang_nam_sinh" CHECK (nam_sinh >= 1900)
);

CREATE TABLE "do_uong" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_do_uong" varchar(30) UNIQUE NOT NULL,
  "ten_do_uong" varchar(150) NOT NULL,
  "mo_ta" text,
  "dang_kinh_doanh" boolean NOT NULL DEFAULT true,
  "ngay_tao" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_do_uong_ten" CHECK (length(trim(ten_do_uong)) > 0)
);

CREATE TABLE "phan_hoi" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "khach_hang_id" bigint NOT NULL,
  "do_uong_id" bigint NOT NULL,
  "so_sao" smallint NOT NULL,
  "noi_dung" text NOT NULL,
  "trang_thai" trang_thai_phan_hoi NOT NULL DEFAULT 'moi',
  "nguoi_xu_ly_id" bigint,
  "ngay_xu_ly" timestamptz,
  "ngay_gui" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_phan_hoi_so_sao" CHECK (so_sao BETWEEN 1 AND 5),
  CONSTRAINT "ck_phan_hoi_noi_dung" CHECK (length(trim(noi_dung)) > 0),
  CONSTRAINT "ck_phan_hoi_xu_ly" CHECK ((trang_thai = 'moi' AND ngay_xu_ly IS NULL AND nguoi_xu_ly_id IS NULL) OR (trang_thai <> 'moi' AND ngay_xu_ly IS NOT NULL)),
  CONSTRAINT "ck_phan_hoi_thoi_gian" CHECK (ngay_xu_ly IS NULL OR ngay_xu_ly >= ngay_gui)
);

CREATE TABLE "khao_sat" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tieu_de" varchar(255) NOT NULL,
  "mo_ta" text,
  "trang_thai" trang_thai_khao_sat NOT NULL DEFAULT 'nhap',
  "nguoi_tao_id" bigint NOT NULL,
  "ngay_tao" timestamptz NOT NULL DEFAULT (now()),
  "ngay_phat_hanh" timestamptz,
  "ngay_ket_thuc" timestamptz,
  "da_an" boolean NOT NULL DEFAULT false,
  CONSTRAINT "ck_khao_sat_tieu_de" CHECK (length(trim(tieu_de)) > 0),
  CONSTRAINT "ck_khao_sat_phat_hanh" CHECK ((trang_thai = 'nhap' AND ngay_phat_hanh IS NULL) OR (trang_thai <> 'nhap' AND ngay_phat_hanh IS NOT NULL)),
  CONSTRAINT "ck_khao_sat_thoi_gian" CHECK (ngay_ket_thuc IS NULL OR ngay_phat_hanh IS NULL OR ngay_ket_thuc > ngay_phat_hanh)
);

CREATE TABLE "cau_hoi" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "khao_sat_id" bigint NOT NULL,
  "noi_dung" text NOT NULL,
  "thu_tu" int NOT NULL,
  "bat_buoc" boolean NOT NULL DEFAULT true,
  CONSTRAINT "ck_cau_hoi_thu_tu" CHECK (thu_tu > 0),
  CONSTRAINT "ck_cau_hoi_noi_dung" CHECK (length(trim(noi_dung)) > 0)
);

CREATE TABLE "lua_chon" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "cau_hoi_id" bigint NOT NULL,
  "noi_dung" varchar(500) NOT NULL,
  "thu_tu" int NOT NULL,
  CONSTRAINT "ck_lua_chon_thu_tu" CHECK (thu_tu > 0),
  CONSTRAINT "ck_lua_chon_noi_dung" CHECK (length(trim(noi_dung)) > 0)
);

CREATE TABLE "phan_phoi_khao_sat" (
  "khao_sat_id" bigint NOT NULL,
  "khach_hang_id" bigint NOT NULL,
  "ngay_gui" timestamptz NOT NULL DEFAULT (now()),
  "ngay_hoan_thanh" timestamptz,
  CONSTRAINT "ck_phan_phoi_thoi_gian" CHECK (ngay_hoan_thanh IS NULL OR ngay_hoan_thanh >= ngay_gui),
